BIMANUAL_ROBOT_PROMPT = """
该机器人为固定底座双机械臂操作机器人，由物理身份固定的左机械臂和右机械臂组成。

对于该机器人，executor 集合固定为 "arm_1" 和 "arm_2"：

- executor="arm_1" 固定表示左机械臂；
- executor="arm_2" 固定表示右机械臂。

这里的左机械臂和右机械臂表示机器人本体上的固定物理身份。编号一旦建立，在完整视频中不得改变。

【身份判定依据】

判断左、右机械臂时，按照以下优先级使用证据：

1. 优先根据机械臂底座、根部位置及其与机器人本体的连接关系确定物理左臂和右臂；
2. 无法看到底座或根部时，根据末端外观、连杆结构、夹爪特征、运动轨迹和遮挡前后连续性判断身份；
3. 上述证据不足时，以 primary_view 中首次可靠出现时的稳定工作区域作为辅助依据：通常位于画面左侧的机械臂对应 arm_1，位于画面右侧的机械臂对应 arm_2；
4. 其他视角只用于辅助确认身份，不得分别按照各自画面的左右位置重新编号。

画面左右位置只用于首次建立身份时的辅助判断，不是持续重新编号的依据。

【非同时出现】

两个机械臂不要求同时出现在同一画面或同一时间段。

- 仅出现左侧机械臂时，将其识别为 arm_1；
- 仅出现右侧机械臂时，将其识别为 arm_2；
- 两个机械臂先后出现时，应分别根据底座、根部、稳定工作区域、外观和轨迹连续性恢复其固定身份；
- 不得因为某个机械臂更早出现，就简单将其定义为 arm_1；
- 不得因为后出现的末端执行器此前未被观察到，就直接将其定义为 arm_2。

【轨迹连续性】

- 同一连续可见的机械臂轨迹必须保持相同 executor；
- 机械臂短暂遮挡或离开画面后重新出现时，应根据出现位置、运动方向、末端外观、末端姿态和夹爪状态恢复原身份；
- 双臂交叉、移动到对侧工作区域或当前画面位置发生变化时，不得交换 arm_1 和 arm_2；
- 已确定为 arm_1 的机械臂后续即使位于画面右侧，仍保持 arm_1；
- 已确定为 arm_2 的机械臂后续即使位于画面左侧，仍保持 arm_2。

【固定输出】

对于 bimanual 机器人，arm_1 和 arm_2 是固定存在的两个 executor。

某个机械臂在当前视频中没有出现或无法被清晰观察时，仍保留对应 executor，但其不可观察的外观、位置等信息应填写“未知”或“未观察到”，不得虚构视觉信息。

当视频证据不足以确认某段观测属于 arm_1 还是 arm_2 时，应保留两个固定 executor，并在当前阶段提供的不确定性或人工复核字段中说明身份歧义，不得随意交换编号。
"""


MOBILE_MANIPULATOR_PROMPT = """
该机器人为移动操作机器人，由一个移动底盘和一个或多个机械臂组成。

【执行主体编号】

- 移动底盘的 executor 使用 "base"。
- 第一个能够可靠区分的机械臂 executor 使用 "arm_1"；能够可靠区分更多机械臂时，依次使用 "arm_2" 等稳定编号。
- 各 executor 编号只用于区分物理执行主体，不表示画面方位。
- executor 编号建立后应保持固定，不因遮挡、离开画面、重新出现或画面位置变化而改变。
- 无法可靠确认某个执行主体的类别或身份时，应标记身份不确定，不得根据机器人能力或任务类型推断。
"""


ROBOT_TYPE_PROMPTS = {
    "single_arm": SINGLE_ARM_ROBOT_PROMPT,
    "bimanual": BIMANUAL_ROBOT_PROMPT,
    "mobile_manipulator": MOBILE_MANIPULATOR_PROMPT,
}


def get_robot_type_prompt(robot_type: str) -> str:
    prompt = ROBOT_TYPE_PROMPTS.get(robot_type)
    if prompt:
        return prompt.strip()
    return (
        '当前 robot_type 为 "unknown"。不要猜测机器人类别，只根据视频中直接可见的结构和身份特征识别执行主体；'
        '无法可靠确认执行主体类别或身份时，executor 使用 "unknown"。'
    )
